import assert from 'node:assert/strict';
import { join } from 'node:path';
import { createServer } from 'vite';
process.env.BROWSER_BASE_URL ??= 'http://localhost:5129';
process.env.BROWSER_API_PORT ??= '3125';
const { createBrowserFixture, databaseUrl, postgres, frontend, workspace } = await import('./fixture.mjs');
let fixture, vite, db;
try {
  vite = await createServer({ root: join(workspace, 'apps/client'), configFile: join(workspace, 'apps/client/vite.config.ts'), server: { port: Number(new URL(frontend).port), strictPort: true, hmr: false, watch: null } });
  await vite.listen();
  fixture = await createBrowserFixture({ name: 'Code Editor' });
  const { page, api, organizations, errors } = fixture;
  const explorer = page.getByTestId('skill-explorer');
  const content = page.locator('[data-slot="code-editor"] .cm-content');
  const read = async () => content.innerText();
  await page.goto(frontend + '/app/skills/builtin%3Atable');
  await explorer.waitFor();
  await content.waitFor();
  assert.equal(await content.getAttribute('aria-readonly'), 'true');
  const original = await read();
  await content.click();
  await page.keyboard.press('ControlOrMeta+a');
  await page.keyboard.insertText('Attempt to edit a platform skill');
  assert.equal(await read(), original, 'builtin content is immutable through native keyboard input');
  assert.equal(await explorer.getByRole('button', { name: '保存', exact: true }).count(), 0);
  assert(await page.locator('.cm-lineNumbers .cm-gutterElement').count() > 1);
  await page.keyboard.press('ControlOrMeta+f');
  await page.locator('.cm-search input[name="search"]').waitFor();
  await page.keyboard.press('Escape');

  db = postgres(databaseUrl);
  const document = '---\nname: editor-proof\ndescription: Local editor fixture\n---\n\n# Original\n';
  const files = [{ path: 'scripts/check.py', content: 'def check():\n    return True\n' }, { path: 'references/config.json', content: '{"enabled": true}\n' }];
  const [skill] = await db`insert into skills (organization_id,name,description,document,files) values (${organizations[0]},'editor-proof','Local editor fixture',${document},${db.json(files)}) returning id`;
  await page.goto(frontend + '/app/skills/' + skill.id);
  await page.waitForFunction(() => document.querySelector('[data-slot="code-editor"] .cm-content')?.getAttribute('aria-readonly') === 'false');
  const edit = async (text) => { await content.click(); await page.keyboard.press('ControlOrMeta+a'); await page.keyboard.insertText(text); };
  const updatedDocument = document + 'Updated instruction.\n';
  await edit(updatedDocument);
  await explorer.getByRole('button', { name: 'check.py', exact: true }).click();
  assert.match(await read(), /return True/);
  await content.click(); await page.keyboard.press('ControlOrMeta+Home'); await page.keyboard.press('Tab');
  assert.match(await read(), /^\s+def check/);
  await page.keyboard.press('ControlOrMeta+z');
  assert.match(await read(), /^def check/);
  const updatedPython = 'def check():\n    return False\n';
  await edit(updatedPython);
  await explorer.getByRole('button', { name: 'SKILL.md', exact: true }).click();
  assert.match(await read(), /Updated instruction/);
  await explorer.getByRole('button', { name: 'check.py', exact: true }).click();
  assert.match(await read(), /return False/);
  await page.route(`**/api/skills/${skill.id}`, route => route.request().method() === 'PATCH' ? route.fulfill({ status: 400, contentType: 'application/json', body: JSON.stringify({ error: 'Fixture save rejected' }) }) : route.fallback());
  await explorer.getByRole('button', { name: '保存', exact: true }).click();
  await explorer.getByRole('alert').getByText('Fixture save rejected', { exact: true }).waitFor();
  assert.match(await read(), /return False/);
  assert.equal((await api('/skills/' + skill.id)).version, 1);
  await page.unroute(`**/api/skills/${skill.id}`);
  await Promise.all([page.waitForResponse(response => response.url().endsWith('/api/skills/' + skill.id) && response.request().method() === 'PATCH' && response.ok()), explorer.getByRole('button', { name: '保存', exact: true }).click()]);
  await page.waitForFunction(() => [...document.querySelectorAll('[data-testid="skill-explorer"] button')].find(button => button.textContent === '保存')?.disabled);
  const saved = await api('/skills/' + skill.id);
  assert.equal(saved.document, updatedDocument);
  assert.equal(saved.files.find(file => file.path === 'scripts/check.py').content, updatedPython);
  assert.equal(saved.files.find(file => file.path === 'references/config.json').content, files[1].content);
  assert.equal(saved.version, 2);
  await edit('Transient draft');
  await explorer.getByRole('button', { name: '取消', exact: true }).click();
  assert.match(await read(), /return False/);
  for (const width of [700, 320]) {
    await page.setViewportSize({ width, height: 700 });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'narrow editor scrolls its code without widening the page');
    await explorer.getByRole('button', { name: 'config.json', exact: true }).click();
    assert.match(await read(), /enabled/);
    await page.locator('[data-slot="code-editor"] .cm-gutters').waitFor();
  }
  assert.deepEqual(errors, []);
  console.log('PASS CodeEditor builtin read-only/search/line numbers, workspace Markdown+Python drafts/indent/undo/failed-save retry/version/files/cancel and narrow layout; no model calls or screenshots');
} finally {
  if (db) await db.end();
  if (fixture) await fixture.close();
  if (vite) await vite.close();
}
