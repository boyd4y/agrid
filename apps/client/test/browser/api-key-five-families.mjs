import assert from 'node:assert/strict';
import { createBrowserFixture, postgres, databaseUrl } from './fixture.mjs';
const f = await createBrowserFixture({ name: 'Calendar CRUD compatibility' });
const { page, api, frontend } = f;
const db = postgres(databaseUrl);
const command = async (command, input) => (await api('/commands', { command, input })).result;
const key = () => crypto.randomUUID();
try {
  const table = await api('/tables', { name: 'Combined content' });
  const workspace = (await command('getWorkspace')).workspace;
  const calendar = await command('createCalendar', { name: 'Legacy calendar', timeZone: 'UTC', idempotencyKey: key() });
  const saved = await api('/user/api-keys', { name: 'Legacy grants', permissions: [{ tableId: table.id, canRead: true, canCreate: false, canUpdate: false, canDelete: false }], calendarPermissions: [{ calendarId: calendar.id, canRead: true, canReadAvailability: false, canCreate: false, canUpdate: false, canCancel: false, canManage: false }] });
  const stored = async () => db`select * from api_key_calendars where key_id=${saved.key.id}`;
  const before = await stored();
  const callKey = async status => {
    const response = await fetch(f.base + '/api/commands', { method: 'POST', headers: { Authorization: `Bearer ${saved.secret}`, 'Content-Type': 'application/json' }, body: JSON.stringify({ command: 'getCalendar', input: { calendarId: calendar.id } }) });
    assert.equal(response.status, status, await response.text());
  };
  await callKey(200);
  await page.goto(frontend + '/app/settings?tab=api-keys');
  const panel = page.getByTestId('api-keys-settings'), dialog = page.getByRole('dialog');
  assert((await panel.getByTestId(`api-key-${saved.key.id}`).innerText()).includes('1 个日历'), 'partial grants count in the scope summary');
  await panel.getByRole('button', { name: '编辑 Legacy grants', exact: true }).click();
  await dialog.getByRole('textbox', { name: '名称', exact: true }).fill('Renamed legacy');
  await dialog.getByRole('checkbox', { name: `${workspace.name} / Combined content · 更新`, exact: true }).check();
  await dialog.getByRole('button', { name: '保存', exact: true }).click(); await dialog.waitFor({ state: 'hidden' });
  assert.deepEqual(await stored(), before, 'renaming and changing tables preserve exact old grants');
  await callKey(200);
  await panel.getByRole('button', { name: '编辑 Renamed legacy', exact: true }).click();
  await dialog.getByRole('tab', { name: '日历', exact: true }).click();
  const read = dialog.getByRole('checkbox', { name: `${workspace.name} / Legacy calendar · 读取`, exact: true });
  assert.equal(await read.getAttribute('aria-checked'), 'mixed');
  await dialog.getByText('混合状态表示旧 Key 仍有该组的部分权限。点击可清除该组，再次勾选才会授予完整权限。', { exact: true }).waitFor();
  await page.screenshot({ path: f.artifact('calendar-legacy-partial.png') });
  await dialog.getByRole('tab', { name: '表格', exact: true }).click();
  for (const operation of ['读取', '更新']) await dialog.getByRole('checkbox', { name: `${workspace.name} / Combined content · ${operation}`, exact: true }).uncheck();
  await dialog.getByRole('tab', { name: '日历', exact: true }).click();
  await read.click();
  assert.equal(await read.getAttribute('aria-checked'), 'false', 'one click clears the mixed group');
  await dialog.getByRole('button', { name: '保存', exact: true }).click(); await dialog.waitFor({ state: 'hidden' });
  assert.equal((await stored()).length, 0, 'last group removal removes the legacy target');
  await callKey(404);
  assert.deepEqual(f.errors, []);
  console.log('PASS calendar CRUD compatibility: partial summary, mixed checkbox, unrelated save preserves exact rows, one-click revoke and live denial.');
} finally { await db.end(); await f.close(); }
