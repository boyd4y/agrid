import assert from 'node:assert/strict';
import { createBrowserFixture } from './fixture.mjs';

const fixture = await createBrowserFixture({ name: 'Personal Key Browser' });
const { page, ctx, api, errors, frontend, base } = fixture;
page.setDefaultTimeout(10000);
const settingsTabs = page.locator('[role=tablist][aria-orientation=vertical]');
const assertListFeedback = async (row, deleteButton) => {
  await page.evaluate(() => document.activeElement?.blur()); await page.mouse.move(0, 0);
  const rowElement = await row.elementHandle(), buttonElement = await deleteButton.elementHandle();
  const idle = await row.evaluate(element => getComputedStyle(element).backgroundColor);
  await row.hover();
  await page.waitForFunction(({ element, idle }) => getComputedStyle(element).backgroundColor !== idle, { element: rowElement, idle });
  await page.mouse.move(0, 0); await page.waitForFunction(({ element, idle }) => getComputedStyle(element).backgroundColor === idle, { element: rowElement, idle });
  await deleteButton.focus();
  await page.waitForFunction(({ element, idle }) => getComputedStyle(element).backgroundColor !== idle, { element: rowElement, idle });
  const semantic = await page.evaluate(() => { const probe = document.createElement('span'); probe.hidden = true; probe.style.color = 'var(--destructive)'; probe.style.backgroundColor = 'color-mix(in oklab, var(--destructive) 10%, transparent)'; document.body.append(probe); const style = getComputedStyle(probe), result = { color: style.color, background: style.backgroundColor }; probe.remove(); return result; });
  await deleteButton.hover();
  await page.waitForFunction(({ element, semantic }) => { const style = getComputedStyle(element); return style.color === semantic.color && style.backgroundColor === semantic.background; }, { element: buttonElement, semantic });
  assert.equal(await deleteButton.locator('svg').evaluate(element => getComputedStyle(element).color), semantic.color, 'trash icon uses the shared destructive color');
  await page.evaluate(() => document.activeElement?.blur()); await page.mouse.move(0, 0);
};
try {
  await page.goto(frontend + '/app/settings?tab=api-keys');
  assert.equal(await page.getByRole('tablist', { name: '设置分类' }).getAttribute('aria-orientation'), 'vertical');
  assert.equal(await settingsTabs.getAttribute('data-variant'), 'navigation');
  const navigationStyles = await settingsTabs.evaluate(list => { const active = list.querySelector('[data-state=active]'), inactive = list.querySelector('[data-state=inactive]'); return { after: getComputedStyle(active, '::after').display, active: getComputedStyle(active).backgroundColor, inactive: getComputedStyle(inactive).backgroundColor }; });
  assert.equal(navigationStyles.after, 'none', 'settings navigation has no dot pseudo-element');
  assert.notEqual(navigationStyles.active, navigationStyles.inactive, 'the active navigation row has a selected background');
  assert.equal(await page.getByRole('tab', { name: 'API Key', exact: true }).getAttribute('aria-selected'), 'true');
  await page.getByText('当前工作区还没有 API Key。', { exact: true }).waitFor();
  const settingsFrame = page.getByTestId('settings-frame');
  assert.equal(await settingsFrame.locator('aside').count(), 1, 'settings share one navigation frame');
  await settingsFrame.getByRole('tabpanel', { name: 'API Key', exact: true }).waitFor();
  let attempts = 0, release;
  const pending = new Promise(resolve => { release = resolve; });
  await page.route('**/api/user/api-keys', async route => {
    if (route.request().method() !== 'POST') return route.fallback();
    attempts++;
    if (attempts === 1) {
      await pending;
      return route.fulfill({ status: 400, contentType: 'application/json', body: JSON.stringify({ error: 'Fixture key creation failed' }) });
    }
    return route.fallback();
  });
  await page.getByRole('button', { name: '创建 API Key', exact: true }).click();
  let dialog = page.getByRole('dialog');
  await dialog.getByLabel('名称', { exact: true }).fill('Browser script');
  await dialog.getByRole('button', { name: '创建 API Key', exact: true }).click();
  await dialog.getByRole('button', { name: '创建中…', exact: true }).waitFor();
  assert.equal(await dialog.getByRole('button', { name: '取消', exact: true }).isDisabled(), true);
  assert.equal(await dialog.getByLabel('名称', { exact: true }).isDisabled(), true);
  await page.keyboard.press('Escape');
  assert.equal(await dialog.isVisible(), true, 'pending creation cannot be dismissed');
  // A second native submit event while the request is pending is guarded too.
  await dialog.locator('form').evaluate(form => form.dispatchEvent(new Event('submit', { bubbles: true, cancelable: true })));
  release();
  await dialog.getByRole('alert').filter({ hasText: 'Fixture key creation failed' }).waitFor();
  assert.equal(attempts, 1);
  assert.equal(await dialog.getByLabel('名称', { exact: true }).inputValue(), 'Browser script');
  await dialog.getByRole('button', { name: '创建 API Key', exact: true }).click();
  await dialog.getByRole('heading', { name: 'API Key 已创建', exact: true }).waitFor();
  const raw = await dialog.getByLabel('API Key', { exact: true }).inputValue();
  assert.match(raw, /^tab_[A-Za-z0-9_-]{43}$/);
  // Clipboard is isolated in this page; neither raw keys nor cookies are logged.
  await page.evaluate(() => { window.__copiedKey = ''; Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async value => { window.__copiedKey = value; } } }); });
  await dialog.getByRole('button', { name: '复制 API Key', exact: true }).click();
  assert.equal(await page.evaluate(() => window.__copiedKey), raw);
  await dialog.getByRole('button', { name: '关闭', exact: true }).last().click();
  assert.equal(await page.locator('input').evaluateAll((inputs, secret) => inputs.some(input => input.value === secret), raw), false);
  assert.equal((await page.locator('body').innerText()).includes(raw), false);
  const list = await api('/user/api-keys');
  assert.equal(list.keys.length, 1); assert.equal(JSON.stringify(list).includes(raw), false);
  const key = list.keys[0];
  assert.equal(Object.hasOwn(key, 'revokedAt'), false, 'key metadata does not expose the removed revocation state');
  assert.equal((await ctx.request.get(base + '/api/tables', { headers: { Authorization: `Bearer ${raw}` } })).status(), 200);
  await page.reload();
  await page.getByRole('button', { name: '删除 Browser script', exact: true }).waitFor();
  assert.equal(await page.getByRole('dialog').count(), 0, 'secret creation stage never comes back after reload');
  const keyDelete = page.getByRole('button', { name: '删除 Browser script', exact: true });
  const keyRow = page.locator('[data-slot=list-item]').filter({ has: keyDelete });
  await assertListFeedback(keyRow, keyDelete);
  await page.getByRole('button', { name: '收起侧栏', exact: true }).click();
  await page.setViewportSize({ width: 320, height: 740 });
  await page.waitForFunction(() => document.querySelector('[data-testid=app-sidebar]').getBoundingClientRect().width <= 57);
  assert.equal(await page.getByRole('tabpanel', { name: 'API Key', exact: true }).evaluate(element => element.scrollWidth <= element.clientWidth + 1), true, '320px persisted key row fits its pane');
  assert.equal(await keyDelete.isVisible(), true);
  await page.setViewportSize({ width: 1600, height: 1000 });
  await page.getByRole('button', { name: '展开侧栏', exact: true }).click();

  await page.getByRole('button', { name: '删除 Browser script', exact: true }).click();
  await page.getByRole('alertdialog').getByRole('button', { name: '取消', exact: true }).click();
  assert.equal((await api('/user/api-keys')).keys[0].id, key.id);
  let deleteAttempts = 0;
  await page.route(`**/api/user/api-keys/${key.id}`, async route => {
    if (route.request().method() !== 'DELETE') return route.fallback();
    if (++deleteAttempts === 1) return route.fulfill({ status: 400, contentType: 'application/json', body: JSON.stringify({ error: 'Fixture deletion failed' }) });
    return route.fallback();
  });
  await page.getByRole('button', { name: '删除 Browser script', exact: true }).click();
  const confirmation = page.getByRole('alertdialog');
  await confirmation.getByRole('button', { name: '删除密钥', exact: true }).click();
  await confirmation.getByRole('alert').filter({ hasText: 'Fixture deletion failed' }).waitFor();
  assert.equal((await api('/user/api-keys')).keys[0].id, key.id);
  await confirmation.getByRole('button', { name: '删除密钥', exact: true }).click();
  await confirmation.waitFor({ state: 'detached' });
  assert.equal(deleteAttempts, 2);
  await page.getByText('当前工作区还没有 API Key。', { exact: true }).waitFor();
  assert.equal((await api('/user/api-keys')).keys.length, 0, 'successful deletion removes the persisted key record');
  assert.equal(await page.getByText('已撤销', { exact: true }).count(), 0);
  assert.equal((await ctx.request.get(base + '/api/tables', { headers: { Authorization: `Bearer ${raw}` } })).status(), 401);
  assert.equal(await page.getByRole('button', { name: '删除 Browser script', exact: true }).count(), 0);
  await page.getByRole('tab', { name: '常规', exact: true }).click();
  assert.equal(await page.getByRole('tabpanel', { name: '常规', exact: true }).getByRole('switch').count(), 0, 'General retains appearance and language without layout switches');
  await page.getByLabel('English', { exact: true }).click();
  await page.getByRole('tab', { name: 'API Key', exact: true }).click();
  await page.getByRole('heading', { name: 'Personal API keys', exact: true }).waitFor();
  // The existing app shell keeps its expanded sidebar on narrow screens; collapse it explicitly.
  await page.getByRole('button', { name: 'Collapse sidebar', exact: true }).click();
  await page.setViewportSize({ width: 320, height: 740 });
  await page.getByRole('tab', { name: 'General', exact: true }).click();
  await page.getByLabel('Dark', { exact: true }).click();
  await page.getByRole('tab', { name: 'API Key', exact: true }).click();
  await page.getByRole('button', { name: 'Create API key', exact: true }).click();
  dialog = page.getByRole('dialog');
  await dialog.getByLabel('Name', { exact: true }).fill('Second key');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false, 'compact settings do not overflow');
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
  assert.equal(await page.getByRole('tabpanel', { name: 'API Key', exact: true }).evaluate(element => element.scrollWidth <= element.clientWidth + 1), true, '320px key panel does not hide local horizontal overflow');
  assert.equal((await api('/user/api-keys')).keys.length, 0, 'cancel never creates a key');
  await page.getByRole('tab', { name: 'AgentMail', exact: true }).click();
  await page.getByRole('tabpanel', { name: 'AgentMail', exact: true }).waitFor();
  assert.equal(await page.getByRole('tabpanel', { name: 'AgentMail', exact: true }).evaluate(element => element.scrollWidth <= element.clientWidth + 1), true, '320px embedded mail settings do not overflow the panel');
  assert.equal(await page.locator('h1').count(), 1, 'embedded mail settings have no nested page header');
  assert.equal(await page.getByTestId('app-sidebar').locator('a[href="/app/integrations"]').count(), 0);
  assert.equal(await settingsTabs.getByRole('tab').count(), 4, 'settings expose General, API Key, AgentMail, and Webhook only');
  assert.equal(await page.getByRole('tab', { name: 'Integrations', exact: true }).count(), 0);
  assert.equal(await page.getByRole('tab', { name: 'Shortcuts', exact: true }).count(), 0);
  await page.reload();
  assert.equal(await page.getByRole('tab', { name: 'AgentMail', exact: true }).getAttribute('aria-selected'), 'true');
  await page.getByRole('tab', { name: 'Webhook', exact: true }).click();
  await page.getByRole('tabpanel', { name: 'Webhook', exact: true }).waitFor();
  await page.waitForURL(url => url.searchParams.get('tab') === 'webhook');
  await page.goBack();
  await page.getByRole('tabpanel', { name: 'AgentMail', exact: true }).waitFor();
  await page.goto(frontend + '/app/integrations');
  await page.waitForURL('**/app/settings?tab=agentmail');
  await page.goto(frontend + '/app/settings?tab=integrations&keep=1');
  await page.waitForURL(url => url.searchParams.get('tab') === 'agentmail' && url.searchParams.get('keep') === '1');
  await page.goto(frontend + '/app/settings?tab=unknown&keep=1');
  await page.waitForURL('**/app/settings?tab=general&keep=1');
  assert.equal(await page.getByRole('tab', { name: 'General', exact: true }).getAttribute('aria-selected'), 'true');
  assert.deepEqual(errors, []);
  console.log('PASS API keys: navigation without dot+selected background, list hover/focus+destructive icon feedback+320px persisted row, guarded creation/failure retry, one-time secret/copy, metadata reload, cancel/delete failure retry+persisted removal, immediate denial, four settings tabs+legacy/deep-link/reload/back navigation, compact English dark form');
} finally { await fixture.close(); }
